"""Build isolated preview worker. Requires glslang and ziglang; no Blender launch."""
from pathlib import Path
import argparse,os,shutil,struct,subprocess,sys
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
p=argparse.ArgumentParser();p.add_argument('--glslang',default=os.environ.get('GLSLANG'));p.add_argument('--zig-path');p.add_argument('--output',type=Path,default=ROOT/'hammerless/core/hlpreview.exe');a=p.parse_args()
tool=a.glslang or shutil.which('glslang') or shutil.which('glslangValidator')
if not tool:raise SystemExit('Set GLSLANG or pass --glslang to compile preview.comp')
spv=HERE/'preview.spv';subprocess.run([tool,'-V','--target-env','vulkan1.2','-o',str(spv),str(HERE/'preview.comp')],check=True)
data=spv.read_bytes();assert len(data)%4==0;words=struct.unpack('<%dI'%(len(data)//4),data)
lines=['/* Generated by build.py from preview.comp. */','static const unsigned int spv_preview[] = {']
lines += ['    '+', '.join('0x%08x'%w for w in words[i:i+8])+',' for i in range(0,len(words),8)]
lines+=['};'];(HERE/'preview.spv.h').write_text('\n'.join(lines)+'\n');spv.unlink()
env=os.environ.copy()
if a.zig_path:env['PYTHONPATH']=str(Path(a.zig_path).resolve())+os.pathsep+env.get('PYTHONPATH','')
a.output.parent.mkdir(parents=True,exist_ok=True)
zig = [str(Path(a.zig_path)/'ziglang/zig.exe')] if a.zig_path else [sys.executable,'-m','ziglang']
subprocess.run(zig+['cc','-O2','-ffp-contract=off','-fno-fast-math','-target','x86_64-windows-gnu','-mcpu=baseline','-I'+str(ROOT/'native/third_party/vulkan'),str(HERE/'main.c'),'-o',str(a.output)],env=env,check=True)
print('Built',a.output,a.output.stat().st_size)
