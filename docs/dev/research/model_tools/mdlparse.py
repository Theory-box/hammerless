"""MDL v49 (L4D2 / Alien Swarm era) reader + animation decoder.

Layouts from Source SDK 2013 public/studio.h (v49); L4D2 adds activity modifiers to seqdesc
(the 'unused' tail in 2013) and STUDIO_FRAMEANIM is checked for but (so far) not decoded.
"""
